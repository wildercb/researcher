"""Briefings API — comprehensive research briefings.

Three generation modes, all producing complete output:
- basic: paper listings + stats (no LLM)
- ollama: paper listings + LLM analysis via local Ollama
- api: paper listings + LLM analysis via Anthropic/OpenAI API
- claude-code: paper listings + analysis generated by Claude Code agent in background
"""

from collections import Counter
from datetime import datetime

from fastapi import APIRouter, BackgroundTasks, Depends
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from apps.api.deps import get_session
from packages.core.models import Item

router = APIRouter(prefix="/api/briefings", tags=["briefings"])

_briefings: list[dict] = []


@router.get("/")
async def list_briefings() -> dict:
    return {"briefings": _briefings}


@router.get("/{briefing_id}")
async def get_briefing(briefing_id: int) -> dict:
    if 0 <= briefing_id < len(_briefings):
        return _briefings[briefing_id]
    return {"error": "not found"}


class GenerateRequest(BaseModel):
    period: str = "daily"
    mode: str = "ollama"  # "basic", "ollama", "api", "claude-code"


@router.post("/generate")
async def generate_briefing(
    req: GenerateRequest,
    background_tasks: BackgroundTasks,
    session: AsyncSession = Depends(get_session),
) -> dict:
    result = await session.execute(
        select(Item).where(Item.relevance_score.isnot(None)).order_by(Item.relevance_score.desc()).limit(50)
    )
    items = result.scalars().all()
    if not items:
        return {"error": "No items with relevance scores. Run calibration first."}

    # Always build the base paper listing
    base_content = _generate_comprehensive_briefing(items, req.period)
    now = datetime.now()

    if req.mode == "basic":
        content = base_content
    elif req.mode == "ollama":
        content = await _generate_llm_analysis(items, req.period, base_content, None)
    elif req.mode == "api":
        model_override = _get_api_model()
        content = await _generate_llm_analysis(items, req.period, base_content, model_override)
    elif req.mode == "claude-code":
        # Background generation — returns immediately, UI polls for result
        briefing_id = len(_briefings)
        briefing = {
            "id": briefing_id,
            "period": req.period,
            "mode": "claude-code",
            "content": base_content,
            "created_at": now.isoformat(),
            "must_read_count": sum(1 for i in items if (i.relevance_score or 0) >= 0.7),
            "on_radar_count": sum(1 for i in items if 0.4 <= (i.relevance_score or 0) < 0.7),
            "generating": True,
        }
        _briefings.insert(0, briefing)
        # Fire background LLM task
        import asyncio
        asyncio.get_event_loop().create_task(
            _background_llm_analysis(briefing_id, items, req.period, base_content)
        )
        return briefing
    else:
        content = base_content

    briefing = {
        "id": len(_briefings),
        "period": req.period,
        "mode": req.mode,
        "content": content,
        "created_at": now.isoformat(),
        "must_read_count": sum(1 for i in items if (i.relevance_score or 0) >= 0.7),
        "on_radar_count": sum(1 for i in items if 0.4 <= (i.relevance_score or 0) < 0.7),
    }
    _briefings.insert(0, briefing)
    return briefing


class SaveBriefingRequest(BaseModel):
    content: str
    period: str = "daily"


@router.post("/save")
async def save_briefing(req: SaveBriefingRequest) -> dict:
    now = datetime.now()
    briefing = {
        "id": len(_briefings),
        "period": req.period,
        "mode": "claude-code",
        "content": req.content,
        "created_at": now.isoformat(),
        "must_read_count": 0,
        "on_radar_count": 0,
    }
    _briefings.insert(0, briefing)
    return briefing


